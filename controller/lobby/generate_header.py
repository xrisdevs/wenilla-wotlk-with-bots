#!/usr/bin/env python3
"""Generate the server's allowlisted templates from the lobby build catalog."""
import json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[2]
builds=json.loads(pathlib.Path(__file__).with_name('builds.json').read_text())
h=['// Generated by controller/lobby/generate_header.py. Talent ranks are zero-based.',
   'struct LobbyBuild { uint8 cls; uint8 spec; std::vector<std::pair<uint32,uint32>> talents; std::vector<uint32> glyphs; std::vector<std::vector<uint32>> actions; };',
   'static std::map<uint32, LobbyBuild> const LobbyBuilds = {']
for b in builds:
 h.append('{%d, {%d, %d, {%s}, {%s}, {%s}}},'%(b['id'],b['classId'],b['id'],','.join('{%d,%d}'%tuple(t) for t in b['talents']),','.join(str(g['id']) for g in sorted(b['glyphs'],key=lambda g:g['minor'])),','.join('{'+','.join(map(str,a['spells']))+'}' for a in b['actions'])))
h.append('};')
(ROOT/'custom/scripts/BotArena/lobby_builds.h').write_text('\n'.join(h)+'\n')
